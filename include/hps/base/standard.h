#ifndef HPS_BASE_STANDARD_H
#define HPS_BASE_STANDARD_H

#include "hps/base/language.h"


#define HPS_MINIMUM_C_STANDARD  HPS_C_STANDARD_C99
#define HPS_LEGACY_C_STANDARD   HPS_C_STANDARD_C89


#if HPS_LANGUAGE_IS_C && HPS_C_STANDARD_VERSION >= HPS_MINIMUM_C_STANDARD

# define HPS_MODERN_C 1
# define HPS_C_LEGACY 0

#else

# define HPS_MODERN_C 0
# define HPS_C_LEGACY HPS_LANGUAGE_IS_C

#endif


#define HPS_C_IS_C99 \
    (HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C99)

#define HPS_C_IS_C11 \
    (HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C11)

#define HPS_C_IS_C17 \
    (HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C17)

#define HPS_C_IS_C23 \
    (HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C23)


#if defined(HPS_REQUIRE_C99)

# if HPS_C_STANDARD_VERSION < HPS_C_STANDARD_C99
#  error "HPS requires C99 or newer"
# endif

#endif


#if HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C23

# define HPS_C_STANDARD_NAME "C23"

#elif HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C17

# define HPS_C_STANDARD_NAME "C17"

#elif HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C11

# define HPS_C_STANDARD_NAME "C11"

#elif HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C99

# define HPS_C_STANDARD_NAME "C99"

#elif HPS_C_STANDARD_VERSION >= HPS_C_STANDARD_C95

# define HPS_C_STANDARD_NAME "C95"

#elif HPS_LANGUAGE_IS_C

# define HPS_C_STANDARD_NAME "C89/C90"

#else

# define HPS_C_STANDARD_NAME "not C"

#endif


#endif /* HPS_BASE_STANDARD_H */
